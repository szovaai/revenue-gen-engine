import { test } from "node:test";
import assert from "node:assert/strict";
import { findPrivateWebsitePackage } from "./private-website-packages";

test("premium five-page website is a $997 CAD payment", () => {
  assert.equal(findPrivateWebsitePackage("premium")?.amountCad, 997);
  assert.equal(findPrivateWebsitePackage("premium")?.priceId, "premium_website_onetime");
});
test("growth website is a $1497 CAD payment", () => {
  assert.equal(findPrivateWebsitePackage("growth")?.amountCad, 1497);
});
test("3D interactive premium website is a $2997 CAD payment", () => {
  assert.equal(findPrivateWebsitePackage("interactive")?.amountCad, 2997);
});
test("unknown packages cannot be selected", () => {
  assert.equal(findPrivateWebsitePackage("made-up"), undefined);
});